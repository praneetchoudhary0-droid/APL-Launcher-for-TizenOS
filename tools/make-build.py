"""Prepares a launcher version for automatic updates.

Run it after every change, before publishing on GitHub:
    python3 tools/make-build.py --notes "what changes, in one sentence"

Writes:
  launcher/version.json  read by the screens (updater.js) to update themselves
  launcher/js/build.js   what the installed version (.wgt) contains
The version comes from launcher/config.xml (version="…" attribute).
"""
import json, os, re, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
L = os.path.join(ROOT, "launcher")

# Load order (boot.js loads them one by one, in this order)
SCRIPTS = [
    "js/diag.js", "js/lang-fr.js", "js/i18n.js", "js/catalog.js", "js/system.js", "js/keys.local.js", "js/liveshelf.js", "js/icons.js",
    "js/apps.js", "js/autoart.js", "js/genart.js", "js/navigation.js", "js/services.js", "js/settings-tree.js", "js/settings.js",
    "js/controlcenter.js", "js/avatars.local.js", "js/profiles.js", "js/devices.js", "js/sources.js", "js/search.js", "js/appmenu.js", "js/aerials.js", "js/screensaver.js", "js/folders.js", "js/switcher.js", "js/widgets.js", "js/overlay.js",
    "js/updater.js", "js/launcher.js", "js/glass.js", "js/preview.js",
]
STYLES = ["css/launcher.css", "css/glass.css"]
LOADER = 1          # raise it when boot.js changes: the screens will ask for APL Launcher Setup
REINSTALL = "1.0.0"  # minimum installed version: raise it when config.xml changes (permissions…)

notes = ""
if "--notes" in sys.argv:
    notes = sys.argv[sys.argv.index("--notes") + 1]

config = open(os.path.join(L, "config.xml"), encoding="utf-8").read()
version = re.search(r'<widget[^>]*\sversion="([^"]+)"', config).group(1)

for s in SCRIPTS + STYLES:
    if ".local." not in s and not os.path.exists(os.path.join(L, s)):
        sys.exit("missing file: " + s)

html = open(os.path.join(L, "index.html"), encoding="utf-8").read()
body = html[html.index("<body"):]
body = body[body.index(">") + 1:]
body = body[:body.index("<!-- Samsung API")].strip()

images = []
LOCAL = ("images/avatars/custom/", "images/avatars/memoji/")   # added by the installer, never published
for root, _, names in os.walk(os.path.join(L, "images")):
    for n in sorted(names):
        rel = os.path.relpath(os.path.join(root, n), L).replace(os.sep, "/")
        if not n.startswith(".") and not rel.startswith(LOCAL):
            images.append(rel)
images.sort()

manifest = {"version": version, "loader": LOADER, "reinstall": REINSTALL, "notes": notes,
            "scripts": SCRIPTS, "styles": STYLES, "body": body, "images": images}
json.dump(manifest, open(os.path.join(L, "version.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1)
open(os.path.join(L, "js", "build.js"), "w", encoding="utf-8").write(
    "/* GENERATED by tools/make-build.py: contents of the installed version. */\n"
    "window.APL_BUILD = " + json.dumps({"version": version, "scripts": SCRIPTS, "images": images}, ensure_ascii=False) + ";\n")
print("version", version, "-", len(SCRIPTS), "scripts,", len(images), "images")
